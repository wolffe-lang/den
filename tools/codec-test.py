#!/usr/bin/env python3
"""Independent codec driver; imports only lane-owned fixtures and stdlib oracles."""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import zlib

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('vectors',ROOT/'tests/codec/vectors.py')
v=importlib.util.module_from_spec(spec);spec.loader.exec_module(v)

def main():
    p=argparse.ArgumentParser();p.add_argument('--binary',default='target/zpipe');p.add_argument('--vectors-only',action='store_true');p.add_argument('--generate-checked',action='store_true')
    a=p.parse_args(); binary=(ROOT/a.binary).resolve();work=ROOT/'target/codec';work.mkdir(exist_ok=True)
    count=0;results=[]
    def call(op,data,cap=2000000,level=1,error=None):
        nonlocal count
        inp=work/'input';out=work/'output';inp.write_bytes(data);out.unlink(missing_ok=True)
        c=subprocess.run([str(binary),op,str(inp),str(out),str(cap),str(level)],capture_output=True,timeout=30)
        count+=1
        if error:
            assert (c.returncode,c.stdout,c.stderr)==(1,b'',(error+'\n').encode()),(op,error,c.returncode,c.stdout,c.stderr)
            assert not out.exists()
            return None
        assert c.returncode==0 and not c.stderr,(op,c.returncode,c.stdout,c.stderr)
        if op=='hash':return c.stdout.decode().strip()
        return out.read_bytes(),list(map(int,c.stdout.split()))
    rows=v.vectors()
    if a.generate_checked:
        def blob(data):return '['+', '.join(str(b)+' as byte' for b in data)+']'
        s=['//! member: false','// Generated by tools/codec-test.py --generate-checked; independent RFC fixtures.','use zlib','fn error_of(input: List[byte], cap: int, raw: bool) -> str {', '    let result = (if raw then zlib.inflate_raw(input, cap) else zlib.inflate(input, cap)) else |e| { return "{e}" }', '    "success {result.consumed}"', '}', 'fn main() -> int ! zlib.InflateErrors {']
        for row in rows:
            op='inflate_raw' if row.get('raw') else 'inflate';name=row['name'];cap=row.get('cap',len(row.get('decoded',b'')))
            s.append('    region sample {')
            s.append('        let input: List[byte] = '+blob(row['encoded']))
            if 'error' in row:
                s.append(f'        assert(error_of(input, {cap}, {str(row.get("raw",False)).lower()}) == "{row["error"]}")')
            else:
                s.append(f'        let result = zlib.{op}(input, {cap})?')
                s.append(f'        let expected: List[byte] = {blob(row["decoded"])}')
                s.append(f'        assert(result.consumed == {row["consumed"]} && result.data.len == expected.len)')
                s.append('        for i in 0..expected.len { assert(result.data[i] == expected[i]) }')
            s.append('    }')
            s.append(f'    print("PASS {name}")')
        s.extend(['    0','}']);(ROOT/'src/zlib_vectors_test.lu').write_text('\n'.join(s)+'\n');print('generated',len(rows));return
    for row in rows:
        op='inflate_raw' if row.get('raw') else 'inflate'
        if 'error' in row:call(op,row['encoded'],row.get('cap',100000),error=row['error'])
        else:
            data,meta=call(op,row['encoded'],len(row['decoded']))
            assert data==row['decoded'] and meta==[row['consumed'],len(data)],row['name']
        print('PASS',row['name'],flush=True)
    if not a.vectors_only:
        for name,raw in v.payloads():
            for level,strategy in [(0,zlib.Z_DEFAULT_STRATEGY),(1,zlib.Z_FIXED),(6,zlib.Z_DEFAULT_STRATEGY)]:
                encoded=v.stream(raw,level,strategy)
                data,meta=call('inflate',encoded,len(raw));assert data==raw and meta==[len(encoded),len(raw)],name
                for short in [0,1,len(encoded)-1]:call('inflate',encoded[:short],len(raw),error='truncated')
            for level in [0,1,-1]:
                for bare in [False,True]:
                    encoded,meta=call('deflate_raw' if bare else 'deflate',raw,len(raw)*2+100,level)
                    d=zlib.decompressobj(-15 if bare else 15);decoded=d.decompress(encoded)+d.flush()
                    assert d.eof and not d.unused_data and decoded==raw,(name,level,bare)
                    if not bare and level==1:
                        oracle=v.stream(raw,1);results.append(dict(name=name,raw=len(raw),den=len(encoded),zlib=len(oracle),ratio=len(encoded)/len(oracle),sha256=hashlib.sha256(raw).hexdigest()))
                    call('deflate_raw' if bare else 'deflate',raw,len(encoded)-1,level,error='limit')
                    exact,_=call('deflate_raw' if bare else 'deflate',raw,len(encoded),level);assert exact==encoded
            for level in [-2,2,6,9,10]:call('deflate',raw,1000000,level,error='unsupported_level')
            call('deflate',raw,-1,error='invalid')
            print('PASS payload',name,flush=True)
    summary=dict(zlib_compile=zlib.ZLIB_VERSION,zlib_runtime=zlib.ZLIB_RUNTIME_VERSION,calls=count,vectors=len(rows),sizes=results)
    (work/'summary.json').write_text(json.dumps(summary,indent=2)+'\n');print(json.dumps(summary),flush=True)
if __name__=='__main__':main()
